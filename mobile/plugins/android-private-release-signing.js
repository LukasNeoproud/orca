const { withAppBuildGradle } = require('expo/config-plugins')

const SIGNING_MARKER = '// @generated by android-private-release-signing'
const DEBUG_SIGNING = 'signingConfig signingConfigs.debug'

function applyPrivateReleaseSigning(contents) {
  if (contents.includes(SIGNING_MARKER)) {
    return contents
  }

  const signingAnchor = 'signingConfigs {'
  const signingIndex = contents.indexOf(signingAnchor)
  if (signingIndex === -1) {
    throw new Error('Expo Android template no longer contains signingConfigs')
  }

  const privateSigningConfig = `${signingAnchor}
        ${SIGNING_MARKER}
        if (System.getenv("ORCA_PRIVATE_ANDROID_SIGNING") == "true") {
            def privateStoreFile = System.getenv("ORCA_PRIVATE_ANDROID_KEYSTORE_PATH")
            def privateStorePassword = System.getenv("ORCA_PRIVATE_ANDROID_KEYSTORE_PASSWORD")
            def privateKeyAlias = System.getenv("ORCA_PRIVATE_ANDROID_KEY_ALIAS")
            def privateKeyPassword = System.getenv("ORCA_PRIVATE_ANDROID_KEY_PASSWORD")
            if (!privateStoreFile || !privateStorePassword || !privateKeyAlias || !privateKeyPassword) {
                throw new GradleException("Private Android signing environment is incomplete")
            }
            privateRelease {
                storeFile file(privateStoreFile)
                storePassword privateStorePassword
                keyAlias privateKeyAlias
                keyPassword privateKeyPassword
            }
        }`

  let next =
    contents.slice(0, signingIndex) +
    contents.slice(signingIndex).replace(signingAnchor, privateSigningConfig)
  const releaseIndex = next.indexOf('release {', next.indexOf('buildTypes {'))
  const releaseSigningIndex = next.indexOf(DEBUG_SIGNING, releaseIndex)
  if (releaseIndex === -1 || releaseSigningIndex === -1) {
    throw new Error('Expo Android template no longer contains release debug signing fallback')
  }

  const privateReleaseSigning =
    'signingConfig System.getenv("ORCA_PRIVATE_ANDROID_SIGNING") == "true" ? signingConfigs.privateRelease : signingConfigs.debug'
  next =
    next.slice(0, releaseSigningIndex) +
    privateReleaseSigning +
    next.slice(releaseSigningIndex + DEBUG_SIGNING.length)
  return next
}

module.exports = function withAndroidPrivateReleaseSigning(config) {
  return withAppBuildGradle(config, (cfg) => {
    if (cfg.modResults.language !== 'groovy') {
      throw new Error('Private Android signing supports the Expo Groovy template only')
    }
    cfg.modResults.contents = applyPrivateReleaseSigning(cfg.modResults.contents)
    return cfg
  })
}

module.exports.applyPrivateReleaseSigning = applyPrivateReleaseSigning
